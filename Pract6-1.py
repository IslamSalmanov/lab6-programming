# Запрос количества элементов в списке
n = int(input("Введит количество символов: "))
# Создание пустых списков
m1 = []
m2 = []
# Заполнение первого списка
print("Заполнение первого списка")
for i in range(n):
    print(f"Элемент: {i+1}")
    a = int(input("Введите элемент: "))
    m1.append(a)
# Заполнение второго списка
print("Заполнение второго списка")
for i in range(n):
    print(f"Элемент: {i+1}")
    a = int(input("Введите элемент: "))
    m2.append(a)
# Множества
m1 = set(m1)
m2 = set(m2)
# Нахождение объединения
ob = m1 | m2
# Нахождение пересечения
per = m1 & m2
# Нахождение разности
raz = m1 - m2
# Вывод результата
print(f"Первый список: {', '.join(map(str, m1))}")
print(f"Второй список: {', '.join(map(str, m2))}")
print(f"Объединение: {', '.join(map(str, ob))}")
print(f"Общие элементы: {', '.join(map(str, per))}")
print(f"Разность: {', '.join(map(str, raz))}")
