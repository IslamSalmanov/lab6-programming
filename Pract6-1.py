# Запрос количества элементов массива
n = int(input("Введите число элементов: "))
# Создание пустого массива
m = []
# Добавление элементов в массив
for i in range(n):
    a = int(input("Введите элемент: "))
    m.append(a)
d = []
for i in range(len(m)):
    # Подсчёт количество повторов
    if m.count(m[i]) > 1:
        # Если дубликат уже добавлен в массив, пропустить его
        if m[i] in d:
            continue
        else:
            d.append(m[i])
# Вывод дубликатов
if len(d) > 0:
    print(f"Дубликаты: {', '.join(map(str, d))}")
else:
    print("Дуюликатов нет")
